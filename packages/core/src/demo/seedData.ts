export function createDemoImpactEvents(referenceDate: string = todayISODate()): ImpactEvent[] {
  const samples: Array<{
    id: string;
    daysAgo: number;
    name: string;
    category: InventoryItem['category'];
    quantity: number;
    unit: InventoryItem['unit'];
    outcome: ImpactEvent['outcome'];
  }> = [
    {
      id: 'imp-1',
      daysAgo: 6,
      name: 'Ground Turkey',
      category: 'meat_poultry',
      quantity: 450,
      unit: 'g',
      outcome: 'saved',
    },
    {
      id: 'imp-2',
      daysAgo: 4,
      name: 'Multigrain Bread',
      category: 'bakery',
      quantity: 350,
      unit: 'g',
      outcome: 'frozen',
    },
    {
      id: 'imp-3',
      daysAgo: 3,
      name: 'Broccoli Florets',
      category: 'produce',
      quantity: 300,
      unit: 'g',
      outcome: 'saved',
    },
    {
      id: 'imp-4',
      daysAgo: 2,
      name: 'Sharp Cheddar Cheese',
      category: 'dairy',
      quantity: 200,
      unit: 'g',
      outcome: 'saved',
    },
    {
      id: 'imp-5',
      daysAgo: 1,
      name: 'Vegetable Curry Leftover',
      category: 'leftovers',
      quantity: 1,
      unit: 'servings',
      outcome: 'saved',
    },
  ];

  return samples.map((s) => {
    const est = estimateItemImpact({
      quantity: s.quantity,
      unit: s.unit,
      category: s.category,
    });
    return {
      id: s.id,
      timestamp: `${addDaysISODate(referenceDate, -s.daysAgo)}T18:30:00.000Z`,
      itemName: s.name,
      category: s.category,
      outcome: s.outcome,
      weightKg: est.weightKg,
      estimatedValueUsd: est.estimatedMoneyUsd,
      estimatedCo2eKg: est.estimatedCo2eKg,
    };
  });
}
